def build_recommendations(ratios: list[RatioResult]) -> list[Recommendation]:
    recs: list[Recommendation] = []
    for r in ratios:
        if not r.applicable or r.value is None or r.benchmark is None:
            continue
        if r.status not in (RatioStatus.attention, RatioStatus.critical):
            continue
        rules = _RULES.get(r.key)
        if not rules:
            continue
        lo, hi = r.benchmark.good
        side = None
        if r.benchmark.direction == "higher":
            side = "low" if r.value < lo else "high"
        elif r.benchmark.direction == "lower":
            side = "high" if r.value > hi else "low"
        else:
            side = "low" if r.value < lo else "high"
        rule = rules.get(side)
        if not rule:
            continue
        priority = rule["priority"]
        if r.status == RatioStatus.critical and priority == "medium":
            priority = "high"
        recs.append(Recommendation(
            problem=rule["problem"], ratio=r.name, current_value=round(r.value, 2),
            benchmark_hint=_rng(r), action=rule["action"],
            expected_effect=rule["effect"], tradeoffs=rule["tradeoffs"],
            priority=priority, difficulty=rule["difficulty"],
        ))
    order = {"high": 0, "medium": 1, "low": 2}
    recs.sort(key=lambda x: order[x.priority])
    return recs[:10]
