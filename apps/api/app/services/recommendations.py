"""Rule-based recommendations derived from computed ratios.

No LLM is required: every recommendation is triggered by a specific ratio
status against the industry benchmark, includes trade-offs and never uses
categorical imperatives.
"""
from __future__ import annotations

from ..schemas import RatioResult, RatioStatus, Recommendation


def _rng(r: RatioResult) -> str:
    if not r.benchmark:
        return "нет отраслевых данных"
    lo, hi = r.benchmark.good
    u = "%" if r.unit == "%" else ""
    if hi >= 1e12:
        return f"желательно ≥ {lo:g}{u} (демо-диапазон)"
    if r.benchmark.direction == "lower" and lo <= 0:
        return f"желательно ≤ {hi:g}{u} (демо-диапазон)"
    return f"желательно {lo:g}–{hi:g}{u} (демо-диапазон)"


